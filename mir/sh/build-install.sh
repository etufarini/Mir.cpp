#!/usr/bin/env bash
# Generate the standalone installer from canonical bootstrap, adapters and core.
set -euo pipefail
ROOT="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd)"
mode=${1:-write}
if [[ "$mode" != write && "$mode" != --check ]] || (( $# > 1 )); then
    printf 'Usage: bash build-install.sh [--check]\n' >&2; exit 1
fi

emit_functions() {
    local file=$1 names=$2 line name copying=false
    while IFS= read -r line; do
        if [[ "$line" =~ ^([a-z_]+)\(\)\ \{ ]]; then
            name=${BASH_REMATCH[1]}
            case " $names " in *" $name "*) copying=true ;; *) copying=false ;; esac
        fi
        if "$copying"; then printf '%s\n' "$line"; fi
        if [[ "$line" == '}' || ( "$line" =~ ^[a-z_]+\(\)\ \{ && "$line" == *'; }' ) ]]; then copying=false; fi
    done < "$file"
}

emit_installer() {
    local line file
    printf '#!/usr/bin/env bash\n# Generated by mir/sh/build-install.sh. Edit the canonical files, then regenerate.\n'
    sed '1d' "$ROOT/lib/platform/macos-bootstrap.sh"
    sed '1d' "$ROOT/lib/runtime.sh"
    while IFS= read -r line; do
        # Shell syntax below is emitted literally, not evaluated here.
        # shellcheck disable=SC2016
        if [[ "$line" == '    source "$MIR_ROOT/lib/platform/$1.sh" || return 1' ]]; then
            # shellcheck disable=SC2016
            printf '    case "$1" in\n        linux)\n'
            emit_functions "$ROOT/lib/platform/linux.sh" 'platform_required_tools platform_browser_command platform_move platform_dependency_hint platform_ensure_dependencies debian_package_manager install_dependency_packages'
            printf '            ;;\n        macos)\n'
            emit_functions "$ROOT/lib/platform/macos.sh" 'platform_required_tools platform_browser_command platform_move platform_dependency_hint platform_ensure_dependencies'
            printf '            ;;\n    esac\n'
        else printf '%s\n' "$line"; fi
    done < <(sed '1d' "$ROOT/lib/platform.sh")
    printf 'runtime_files() {\n    printf '\''%%s\\n'\'' mir.sh dialogrc sh/uninstall.sh lib/gguf.py'
    for file in "$ROOT"/lib/*.sh "$ROOT"/lib/tui/*.sh; do
        printf ' %q' "${file#"$ROOT"/}"
    done
    printf '\n'
    # shellcheck disable=SC2016 # Bundle only files for the selected target OS.
    printf '    case "$PLATFORM_ID" in\n        linux) printf '\''%%s\\n'\'' lib/platform/linux.sh ;;\n        macos) printf '\''%%s\\n'\'' lib/platform/macos.sh lib/platform/macos-bootstrap.sh ;;\n    esac\n}\n'
    sed '1d' "$ROOT/sh/install-core.sh"
}

if [[ "$mode" == --check ]]; then
    temporary=$(mktemp "${TMPDIR:-/tmp}/mir-installer.XXXXXXXX")
else
    temporary=$(mktemp "$ROOT/sh/.install.XXXXXXXX")
fi
trap 'rm -f -- "$temporary"' EXIT
emit_installer > "$temporary"
"$BASH" -n "$temporary"
if [[ "$mode" == --check ]]; then
    cmp -s "$temporary" "$ROOT/sh/install.sh" || { printf 'Installer is out of sync. Run: bash mir/sh/build-install.sh\n' >&2; exit 1; }
    printf 'PASS: standalone installer matches canonical sources\n'
else
    chmod 644 "$temporary"
    mv -f -- "$temporary" "$ROOT/sh/install.sh"
fi
